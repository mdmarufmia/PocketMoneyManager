    private void editButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editButtonActionPerformed
        int selectedRow = historyTable.getSelectedRow();

        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a transaction to edit.",
                    "Edit Transaction",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        MoneyManager manager = PocketMoneyManager.moneyManager;

        // Table displays newest transaction first,
        // so convert table row to actual record index.
        int recordIndex
                = manager.getRecordCount() - 1 - selectedRow;

        EditTransactionFrame editFrame
                = new EditTransactionFrame(this, recordIndex);

        editFrame.setVisible(true);
    }//GEN-LAST:event_editButtonActionPerformed

