    public void loadHistory() {

        MoneyManager manager = PocketMoneyManager.moneyManager;

        MoneyRecord[] records = manager.getRecords();
        int count = manager.getRecordCount();

        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"Type", "Amount", "Description", "Date"},
                0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        // Show newest transaction first
        for (int i = count - 1; i >= 0; i--) {

            MoneyRecord record = records[i];

            model.addRow(new Object[]{
                record.getRecordType(),
                String.format("%.2f", record.getAmount()),
                record.getDescription(),
                record.getDate()
            });
        }

        historyTable.setModel(model);

        // Make columns easier to read
        historyTable.getColumnModel().getColumn(0).setPreferredWidth(100);
        historyTable.getColumnModel().getColumn(1).setPreferredWidth(100);
        historyTable.getColumnModel().getColumn(2).setPreferredWidth(250);
        historyTable.getColumnModel().getColumn(3).setPreferredWidth(120);

        if (count == 0) {
            return;
        }
    }

